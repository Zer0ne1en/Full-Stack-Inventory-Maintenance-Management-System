-- =====================================================================
-- Mainspring CMMS — initial schema (PostgreSQL 14+)
--
-- Design notes
--  * Identity columns for surrogate keys.
--  * CHECK constraints back up the service layer: stock can never go negative
--    at the database level, even if a bug bypasses the application check.
--  * Partial indexes keep the hot paths (unread alerts, open tickets) fast.
-- =====================================================================

CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(150)  NOT NULL,
    password_hash VARCHAR(100)  NOT NULL,
    role          VARCHAR(20)   NOT NULL,
    enabled       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ   NOT NULL,
    updated_at    TIMESTAMPTZ,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'TECHNICIAN', 'VIEWER'))
);

CREATE TABLE machines
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(120)  NOT NULL,
    code                  VARCHAR(40)   NOT NULL,
    manufacturer          VARCHAR(120),
    model                 VARCHAR(120),
    location              VARCHAR(120),
    status                VARCHAR(30)   NOT NULL DEFAULT 'OPERATIONAL',
    installed_on          DATE,
    last_service_at       DATE,
    next_service_at       DATE,
    service_interval_days INTEGER       NOT NULL DEFAULT 90,
    notes                 VARCHAR(1000),
    created_at            TIMESTAMPTZ   NOT NULL,
    updated_at            TIMESTAMPTZ,
    CONSTRAINT uq_machines_code UNIQUE (code),
    CONSTRAINT ck_machines_status CHECK (status IN ('OPERATIONAL', 'UNDER_MAINTENANCE', 'OUT_OF_SERVICE')),
    CONSTRAINT ck_machines_interval CHECK (service_interval_days >= 0)
);

CREATE TABLE spare_parts
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku               VARCHAR(40)   NOT NULL,
    name              VARCHAR(150)  NOT NULL,
    description       VARCHAR(1000),
    category          VARCHAR(80),
    unit_of_measure   VARCHAR(20)   NOT NULL DEFAULT 'pcs',
    quantity_on_hand  INTEGER       NOT NULL DEFAULT 0,
    reorder_threshold INTEGER       NOT NULL DEFAULT 0,
    unit_price        NUMERIC(12, 2),
    created_at        TIMESTAMPTZ   NOT NULL,
    updated_at        TIMESTAMPTZ,
    CONSTRAINT uq_spare_parts_sku UNIQUE (sku),
    -- The database-level guarantee behind "stock never goes negative".
    CONSTRAINT ck_parts_quantity_non_negative CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_parts_threshold_non_negative CHECK (reorder_threshold >= 0),
    CONSTRAINT ck_parts_price_non_negative CHECK (unit_price IS NULL OR unit_price >= 0)
);

CREATE TABLE maintenance_tickets
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_code             VARCHAR(30)   NOT NULL,
    title                   VARCHAR(150)  NOT NULL,
    description             VARCHAR(2000),
    machine_id              BIGINT        NOT NULL REFERENCES machines (id),
    assigned_technician_id  BIGINT        REFERENCES users (id),
    created_by_id           BIGINT        REFERENCES users (id),
    status                  VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    priority                VARCHAR(20)   NOT NULL DEFAULT 'MEDIUM',
    opened_at               TIMESTAMPTZ   NOT NULL,
    closed_at               TIMESTAMPTZ,
    resolution              VARCHAR(2000),
    created_at              TIMESTAMPTZ   NOT NULL,
    updated_at              TIMESTAMPTZ,
    CONSTRAINT uq_ticket_code UNIQUE (ticket_code),
    CONSTRAINT ck_ticket_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED')),
    CONSTRAINT ck_ticket_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);

CREATE INDEX idx_ticket_status ON maintenance_tickets (status);
CREATE INDEX idx_ticket_machine ON maintenance_tickets (machine_id);
CREATE INDEX idx_ticket_technician ON maintenance_tickets (assigned_technician_id);

CREATE TABLE ticket_part_usages
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     BIGINT        NOT NULL REFERENCES maintenance_tickets (id),
    part_id       BIGINT        NOT NULL REFERENCES spare_parts (id),
    quantity_used INTEGER       NOT NULL,
    unit_cost     NUMERIC(12, 2),
    logged_by_id  BIGINT        REFERENCES users (id),
    logged_at     TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_usage_quantity_positive CHECK (quantity_used > 0)
);

CREATE INDEX idx_usage_ticket ON ticket_part_usages (ticket_id);
CREATE INDEX idx_usage_part ON ticket_part_usages (part_id);

CREATE TABLE alerts
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type      VARCHAR(30)   NOT NULL,
    severity        VARCHAR(20)   NOT NULL DEFAULT 'WARNING',
    title           VARCHAR(200)  NOT NULL,
    message         VARCHAR(1000) NOT NULL,
    reference_type  VARCHAR(60),
    reference_id    BIGINT,
    recipient_email VARCHAR(150),
    emailed_at      TIMESTAMPTZ,
    read_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_alert_type CHECK (alert_type IN ('LOW_STOCK', 'SERVICE_DUE', 'TICKET_OVERDUE')),
    CONSTRAINT ck_alert_severity CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL'))
);

CREATE INDEX idx_alert_read ON alerts (read_at);
CREATE INDEX idx_alert_type_ref ON alerts (alert_type, reference_id);
-- Only one unread alert per (type, reference) — the de-duplication guarantee.
CREATE UNIQUE INDEX uq_alert_unread ON alerts (alert_type, reference_id) WHERE read_at IS NULL;

CREATE TABLE audit_logs
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_name  VARCHAR(100),
    actor_role  VARCHAR(20),
    action      VARCHAR(60)   NOT NULL,
    entity      VARCHAR(60)   NOT NULL,
    entity_id   BIGINT,
    details     VARCHAR(1000),
    ip          VARCHAR(64),
    created_at  TIMESTAMPTZ   NOT NULL
);

CREATE INDEX idx_audit_entity ON audit_logs (entity, entity_id);
CREATE INDEX idx_audit_created ON audit_logs (created_at);
